namespace Poe2Accessibility.Services
{
    using System;
    using System.Collections.Generic;
    using System.IO;
    using System.Linq;
    using System.Text;
    using System.Text.RegularExpressions;
    using Newtonsoft.Json;

    /// <summary>
    ///     Named tiles per area ("G1_2": { tile key: "Mud Burrow" }): the exits and places a player is told about
    ///     before the game has loaded them as entities. GameHelper's Radar ships such a table
    ///     (important_tgt_files.txt); catalog/landmarks.json adds areas it lacks and corrects its labels. A key without the ":x-y:y"
    ///     sub-tile suffix names the whole tile (its centre is used). A label that is exactly an English world-area
    ///     name is spoken in the game's language from catalog/area-names.json (generated by
    ///     `Poe2UiExtract areas` from the game's own Data/Balance/*/WorldAreas.datc64 files), found beside any
    ///     loaded file. Any piece of a label (cut at " - ", slashes, ampersands, commas and brackets) that is a name the game
    ///     has, an area, a monster or NPC (catalog/monster-names.json, `Poe2UiExtract monster-names`), an object title or an item,
    ///     is spoken as the game names it in the client's language, whatever the label's case or apostrophes.
    /// </summary>
    public sealed class LandmarkTable
    {
        private static readonly IReadOnlyDictionary<string, string> None = new Dictionary<string, string>();

        private readonly Dictionary<string, Dictionary<string, string>> areas = new(StringComparer.Ordinal);
        private readonly Dictionary<string, Dictionary<string, string>> names = new(StringComparer.Ordinal);
        private readonly Dictionary<string, string> englishToId = new(StringComparer.Ordinal);
        private readonly HashSet<string> areaNames = new(StringComparer.Ordinal);
        private readonly Dictionary<(string Area, string Language), IReadOnlyDictionary<string, string>> localized = new();
        private readonly Dictionary<string, Dictionary<string, string>> monsterNames = new(StringComparer.Ordinal);
        private readonly Dictionary<string, Dictionary<string, string>> worldTitles = new(StringComparer.Ordinal);
        private readonly Dictionary<string, Dictionary<string, string>> itemNames = new(StringComparer.Ordinal);
        private readonly Dictionary<string, IReadOnlyDictionary<string, string>> gameNames = new(StringComparer.Ordinal);
        private readonly object gameNamesLock = new();
        private readonly HashSet<string> namesLoaded = new(StringComparer.OrdinalIgnoreCase);

        public static LandmarkTable Load(PluginLog log, params string[] files)
        {
            var table = new LandmarkTable();
            foreach (var file in files)
            {
                table.LoadAreaNames(log, Path.Join(Path.GetDirectoryName(file) ?? string.Empty, "area-names.json"));
                table.LoadByLanguage(log, Path.Join(Path.GetDirectoryName(file) ?? string.Empty, "monster-names.json"), table.monsterNames, "boss names");
                table.LoadByLanguage(log, Path.Join(Path.GetDirectoryName(file) ?? string.Empty, "world-titles.json"), table.worldTitles, "object titles");
                table.LoadByLanguage(log, Path.Join(Path.GetDirectoryName(file) ?? string.Empty, "item-names.json"), table.itemNames, "item names");
                if (!File.Exists(file))
                {
                    continue;
                }

                try
                {
                    var parsed = JsonConvert.DeserializeObject<Dictionary<string, Dictionary<string, string>>>(File.ReadAllText(file)) ?? new();
                    foreach (var (area, tiles) in parsed)
                    {
                        if (!table.areas.TryGetValue(area, out var merged))
                        {
                            table.areas[area] = merged = new Dictionary<string, string>(StringComparer.Ordinal);
                        }

                        foreach (var (tile, label) in tiles)
                        {
                            merged[tile] = label;
                        }
                    }

                    log.Info($"Landmarks: {parsed.Count} areas from {file}");
                }
                catch (Exception ex) when (ex is IOException or JsonException)
                {
                    log.Warn($"Landmarks: cannot read {file}: {ex.Message}");
                }
            }

            return table;
        }

        /// <summary>The area's labels as the tables write them (English), for judging what a tile is.</summary>
        public IReadOnlyDictionary<string, string> Source(string areaId) => this.areas.TryGetValue(areaId, out var tiles) ? tiles : None;

        public IReadOnlyDictionary<string, string> For(string areaId)
        {
            if (!this.areas.TryGetValue(areaId, out var tiles))
            {
                return None;
            }

            if (this.names.Count == 0 || !this.names.ContainsKey(Localization.Language))
            {
                return tiles;
            }

            var key = (areaId, Localization.Language);
            if (!this.localized.TryGetValue(key, out var result))
            {
                var map = new Dictionary<string, string>(tiles.Count, StringComparer.Ordinal);
                foreach (var (tile, label) in tiles)
                {
                    map[tile] = this.Localize(label);
                }

                this.localized[key] = result = map;
            }

            return result;
        }

        /// <summary>
        ///     The label names a world area, in any language (an exit before the game loads it), not the radar table's
        ///     own note on a tile ("Ogham Farmlands Or Deadend", "The Corpse Tree (waypoint)").
        /// </summary>
        public bool IsAreaName(string label) => this.areaNames.Contains(label.Trim());

        /// <summary>
        ///     The label in the current language: a name the game has (a whole label or any piece of it) as the game
        ///     names it, a common word of the table translated, then the radar table's own words and reward notes
        ///     (<see cref="Announcements.LandmarkLabel"/>). What is none of these stays as written.
        /// </summary>
        public string Localize(string label)
        {
            var names = this.GameNames(Localization.Language);
            if (names.TryGetValue(Key(label), out var whole))
            {
                return whole;
            }

            // A name that holds a comma ("Mektul, The Forgemaster") is whole before the note in brackets.
            var note = label.IndexOf(" (", StringComparison.Ordinal);
            if (note > 0 && names.TryGetValue(Key(label[..note]), out var baseName))
            {
                return Announcements.LandmarkLabel(baseName + label[note..]);
            }

            var parts = PieceBreaks.Split(label);
            for (var i = 0; i < parts.Length; i += 2)
            {
                var piece = parts[i].Trim();
                if (piece.Length == 0)
                {
                    continue;
                }

                var local = names.TryGetValue(Key(piece), out var named) ? named : MatchCase(piece, Announcements.LandmarkPiece(piece));
                if (local != null)
                {
                    parts[i] = parts[i].Replace(piece, local, StringComparison.Ordinal);
                }
            }

            return Announcements.LandmarkLabel(string.Concat(parts));
        }

        /// <summary>
        ///     The label's pieces that are no name the game has and no common word: what still reads as the table wrote it
        ///     (used to measure how much of the table speaks the game's language).
        /// </summary>
        public IEnumerable<string> UnnamedPieces(string label)
        {
            var names = this.GameNames(Localization.Language);
            if (names.ContainsKey(Key(label)))
            {
                yield break;
            }

            foreach (var piece in PieceBreaks.Split(label).Where((_, i) => i % 2 == 0).Select(piece => piece.Trim()).Where(piece => piece.Length > 0))
            {
                if (!names.ContainsKey(Key(piece)) && Announcements.LandmarkPiece(piece) == null)
                {
                    yield return piece;
                }
            }
        }

        /// <summary>Whether a label or any piece of it is a name the game has (an area, monster, NPC, object or item).</summary>
        public bool HasGameName(string label)
        {
            var names = this.GameNames(Localization.Language);
            return names.ContainsKey(Key(label)) || PieceBreaks.Split(label).Where((_, i) => i % 2 == 0).Any(piece => names.ContainsKey(Key(piece)));
        }

        /// <summary>A translated common word starts in lower case where the piece it replaces does ("(waypoint)").</summary>
        private static string? MatchCase(string piece, string? word) =>
            word is { Length: > 0 } && char.IsLower(piece[0]) ? char.ToLowerInvariant(word[0]) + word[1..] : word;

        /// <summary>A name compared without case, apostrophes, spaces or punctuation ("Lesser jewellers orb" is "Lesser Jeweller's Orb").</summary>
        private static string Key(string text)
        {
            var key = new StringBuilder(text.Length);
            foreach (var letter in text)
            {
                if (char.IsLetterOrDigit(letter))
                {
                    key.Append(char.ToLowerInvariant(letter));
                }
            }

            return key.ToString();
        }

        /// <summary>
        ///     Every English name the catalogs hold (areas first, then monsters and NPCs, object titles, items) mapped to
        ///     the same name in <paramref name="language"/>; built once per language.
        /// </summary>
        private IReadOnlyDictionary<string, string> GameNames(string language)
        {
            lock (this.gameNamesLock)
            {
                if (this.gameNames.TryGetValue(language, out var built))
                {
                    return built;
                }

                var map = new Dictionary<string, string>(StringComparer.Ordinal);
                AddByIdentity(map, this.names, language);
                if (this.monsterNames.TryGetValue(language, out var monsters))
                {
                    foreach (var (label, local) in monsters)
                    {
                        AddName(map, label, local);
                    }
                }

                if (this.worldTitles.TryGetValue("en", out var titlesEn) && this.worldTitles.TryGetValue(language, out var titlesLocal))
                {
                    foreach (var (path, english) in titlesEn)
                    {
                        if (!path.Contains(':') && titlesLocal.TryGetValue(path, out var local))
                        {
                            AddName(map, english, local);
                        }
                    }
                }

                AddByIdentity(map, this.itemNames, language);
                this.gameNames[language] = map;
                return map;
            }
        }

        /// <summary>Adds a name under its key, and without a leading "The" (the table writes "Galai Gates" for "The Galai Gates").</summary>
        private static void AddName(Dictionary<string, string> map, string english, string local)
        {
            map.TryAdd(Key(english), local);
            if (english.StartsWith("The ", StringComparison.OrdinalIgnoreCase))
            {
                map.TryAdd(Key(english[4..]), local);
            }
        }

        /// <summary>English name to the language's name for rows that share an id.</summary>
        private static void AddByIdentity(Dictionary<string, string> map, Dictionary<string, Dictionary<string, string>> byLanguage, string language)
        {
            if (!byLanguage.TryGetValue("en", out var english) || !byLanguage.TryGetValue(language, out var local))
            {
                return;
            }

            foreach (var (id, name) in english)
            {
                if (local.TryGetValue(id, out var translated) && name.Length > 0 && translated.Length > 0)
                {
                    AddName(map, name, translated);
                }
            }
        }

        /// <summary>Where a label breaks into pieces: " - ", slashes, ampersands, commas and brackets (the separators are kept).</summary>
        private static readonly Regex PieceBreaks = new(@"( - | / | & |, |\(|\))", RegexOptions.Compiled);

        /// <summary>
        ///     The name an object shows only in its WorldDescription, in the client's language, empty for none
        ///     (catalog/world-titles.json, `Poe2UiExtract world-titles`).
        /// </summary>
        public string WorldTitle(string path) => this.Title(FileOf(path));

        /// <summary>What the Trial's honour line starts with in the client's language, empty when the table has none.</summary>
        public string HonourLabel => this.Title("label:honour");

        /// <summary>The Trial's sacred water in the client's language, empty when the table has none.</summary>
        public string WaterLabel => this.Title("label:water");

        /// <summary>The line an unallocated passive's tooltip ends with in the client's language, empty when the table has none.</summary>
        public string UnallocatedLabel => this.Title("label:unallocated");

        /// <summary>A world map pin popup's "Monster Level: {0}" in the client's language, empty when the table has none.</summary>
        public string PinLevelLabel => this.Title("label:pin-level");

        /// <summary>A town pin popup's "Town" in the client's language, empty when the table has none.</summary>
        public string PinTownLabel => this.Title("label:pin-town");

        /// <summary>The tracker line without which an object means nothing, empty for most.</summary>
        public string ObjectiveOf(string path) => this.Title("objective:" + FileOf(path));

        private static string FileOf(string path)
        {
            var at = path.IndexOf('@');
            return (at < 0 ? path : path[..at]).ToLowerInvariant();
        }

        private string Title(string key) =>
            this.worldTitles.TryGetValue(Localization.Language, out var titles) && titles.TryGetValue(key, out var title) ? title : string.Empty;

        private void LoadByLanguage(PluginLog log, string file, Dictionary<string, Dictionary<string, string>> table, string what)
        {
            if (!this.namesLoaded.Add(file) || !File.Exists(file))
            {
                return;
            }

            try
            {
                var parsed = JsonConvert.DeserializeObject<Dictionary<string, Dictionary<string, string>>>(File.ReadAllText(file)) ?? new();
                foreach (var (language, byLabel) in parsed)
                {
                    table[language] = byLabel.ToDictionary(pair => pair.Key, pair => pair.Value.Trim(), StringComparer.Ordinal);
                }

                log.Info($"Landmarks: {what} for {parsed.Count} languages from {file}");
            }
            catch (Exception ex) when (ex is IOException or JsonException)
            {
                log.Warn($"Landmarks: cannot read {file}: {ex.Message}");
            }
        }

        private void LoadAreaNames(PluginLog log, string file)
        {
            if (!this.namesLoaded.Add(file) || !File.Exists(file))
            {
                return;
            }

            try
            {
                var parsed = JsonConvert.DeserializeObject<Dictionary<string, Dictionary<string, string>>>(File.ReadAllText(file)) ?? new();
                foreach (var (language, byId) in parsed)
                {
                    // A table regenerated from the game's files keeps the trailing spaces some names carry there.
                    this.names[language] = byId.ToDictionary(pair => pair.Key, pair => pair.Value.Trim(), StringComparer.Ordinal);
                    this.areaNames.UnionWith(this.names[language].Values);
                }

                if (parsed.TryGetValue("en", out var en))
                {
                    foreach (var (id, name) in en)
                    {
                        // First id wins when several areas share a name (e.g. act variants): any one maps to the same text.
                        this.englishToId.TryAdd(name.Trim(), id);
                    }
                }

                log.Info($"Landmarks: area names for {parsed.Count} languages from {file}");
            }
            catch (Exception ex) when (ex is IOException or JsonException)
            {
                log.Warn($"Landmarks: cannot read {file}: {ex.Message}");
            }
        }
    }
}
